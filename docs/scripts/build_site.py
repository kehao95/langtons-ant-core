#!/usr/bin/env python3
"""Assemble the static proof labs and exact manuscript snapshots for Pages."""
import argparse,hashlib,json,shutil,subprocess
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
PAPERS={
 'one-black':'one_black',
 'clock':'clock_escape',
 'wake':'wake_synthesis',
 'factors':'factor_language',
 'memory':'memory_feedback',
 'ports':'four_cell_port',
}
def build(destination):
    # Only replace a generated site directory, never source or a containing path.
    if destination.exists():
        if not (destination/'.proof-labs-build').is_file():
            raise SystemExit('Output exists without the proof-labs build marker: '+str(destination))
        shutil.rmtree(destination)
    destination.mkdir(parents=True)
    (destination/'.proof-labs-build').write_text('Generated by docs/scripts/build_site.py\n')
    docs=ROOT/'docs'
    for p in docs.iterdir():
        if p.name in {'node_modules','scripts','tests','package.json','package-lock.json','sources.json'} or p.suffix=='.md':continue
        target=destination/p.name
        if p.is_dir():shutil.copytree(p,target,ignore=shutil.ignore_patterns('__pycache__','*.pyc'))
        elif p.is_file():shutil.copy2(p,target)
    (destination/'.nojekyll').touch()
    papers=destination/'papers';papers.mkdir()
    manifest={'repository':'https://github.com/kehao95/langtons-ant-core','source_commit':subprocess.check_output(['git','rev-parse','HEAD'],cwd=ROOT,text=True).strip(),'papers':{}}
    publications=json.loads((ROOT/'publications.json').read_text())
    for name,project in PAPERS.items():
        article=publications[project]
        source=article['pdf']
        p=ROOT/source;shutil.copy2(p,papers/(name+'.pdf'))
        digest=hashlib.sha256(p.read_bytes()).hexdigest()
        assert digest==article['pdf_sha256'], 'Article PDF differs from catalog: '+project
        entry={'path':'papers/'+name+'.pdf','source':source,'sha256':digest,
               'doi':article['doi'],'record_url':'https://doi.org/'+article['doi']}
        manifest['papers'][name]=entry
    (destination/'site-manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(f'Assembled {destination}: seven pages, six manuscript snapshots.')
def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--output',type=Path,default=ROOT/'_site');args=ap.parse_args();out=args.output.resolve()
    if out==ROOT or out in ROOT.parents or out==ROOT/'docs' or ROOT/'docs' in out.parents:
        ap.error('Output must be separate from source docs.')
    build(out)
if __name__=='__main__':main()
