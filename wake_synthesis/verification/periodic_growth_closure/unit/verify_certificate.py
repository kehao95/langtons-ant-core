"""Small independent proof-certificate checker. Standard library only.
It does not import the generator, run a solver, or trust a period cutoff.
Every child is regenerated by whole-string combinations, and every terminal
branch has a locally checkable rejection witness.
"""
from __future__ import annotations
import argparse, json, hashlib
from itertools import combinations
from collections import Counter
from pathlib import Path

VECTORS=((0,1),(1,0),(0,-1),(-1,0))

def insist(condition,message):
    if not condition:raise ValueError(message)

def reconstruct(strings):
    """Create all ports first; match geometric directed edges only afterwards."""
    nodes=[(0,0,1)] # transverse level, stable rank, incoming heading
    labels={0:[0]}
    for depth,string in enumerate(strings,1):
        t=-depth;labels[t]=[]
        insist(set(string)<=set('01'),'Non-binary arrival string')
        for k,letter in enumerate(string):
            lower_in=letter=='0'
            h=(1 if lower_in else 3) if t%2==0 else (0 if lower_in else 2)
            labels[t].append(len(nodes));nodes.append((t,k,h))
    size=len(nodes);succ=[-1]*size;pred=[-1]*size;volt=[0]*size
    lo=min(labels)
    for t,ids in labels.items():
        for h,(dx,dy) in enumerate(VECTORS):
            target=t+dx+dy
            sources=[i for i in ids if (nodes[i][2]+(1 if nodes[i][1]%2==0 else -1))%4==h]
            if target>0:insist(not sources,'Step above top rail')
            if target not in labels:continue
            receivers=[j for j in labels[target] if nodes[j][2]==h]
            insist(len(sources)==len(receivers),'Ordered port count mismatch')
            for i,j in zip(sources,receivers):
                insist(succ[i]<0 and pred[j]<0,'Duplicated matching')
                succ[i]=j;pred[j]=i;volt[i]=dx
    return nodes,labels,succ,pred,volt

def extensions(strings):
    nodes,labels,succ,pred,volt=reconstruct(strings)
    t=-len(strings)-1;old=labels[t+1]
    I=sum((nodes[i][2]+(1 if nodes[i][1]%2==0 else -1))%4 in(2,3) for i in old)
    J=sum(nodes[i][2] in(0,1) for i in old)
    # Every L visit at an even level and every R visit at an odd level
    # contributes at least one processed-side incidence: floor(m/2)<=I+J.
    for m in range(2*(I+J)+2):
        if I>m:continue
        for selected in combinations(range(m),I):
            ones=set(selected);s=''.join('1'if k in ones else'0'for k in range(m))
            down_processed=sum(((int(b)^(k%2)) if t%2==0 else 1-(int(b)^(k%2)))for k,b in enumerate(s))
            if down_processed==J:yield strings+(s,)

def chains_of(graph):
    nodes,labels,succ,pred,volt=graph;n=len(nodes)
    component=[-1]*n;index=[0]*n;shift=[0]*n;chains=[]
    for root in range(n):
        if pred[root]>=0:continue
        row=[];i=root;v=0
        while i>=0:
            insist(component[i]<0,'Chains intersect')
            component[i]=len(chains);index[i]=len(row);shift[i]=v;row.append(i)
            v+=volt[i];i=succ[i]
        chains.append(row)
    insist(all(c>=0 for c in component),'Uncertified closed component')
    return component,index,shift,chains

def validate_negative(graph,record):
    nodes,labels,succ,pred,volt=graph;n=len(nodes);kind=record['kind']
    if kind=='closed':
        cycle=record['nodes'];insist(bool(cycle) and len(set(cycle))==len(cycle),'Non-simple phase component')
        insist(all(0<=i<n for i in cycle),'Bad event index')
        insist(all(succ[i]==cycle[(k+1)%len(cycle)]for k,i in enumerate(cycle)), 'Not a fixed directed cycle')
        # The physical theorem supplies a mandatory unbuilt lower layer.
        return
    c,p,v,chains=chains_of(graph)
    if kind=='order':
        pairs=record['pairs'];insist(bool(pairs),'Empty chronological circuit')
        edges=[]
        for i,j in pairs:
            insist(0<=i<n and 0<=j<n,'Bad chronology event')
            ti,ki,_=nodes[i];tj,kj,_=nodes[j]
            insist(ti==tj and kj==ki+1,'Constraint is not consecutive same-class ranks')
            edges.append((c[i],c[j],v[j]-v[i],4+p[i]-p[j]))
        insist(all(edges[k][1]==edges[(k+1)%len(edges)][0]for k in range(len(edges))),'Unclosed root-time circuit')
        K=sum(x[2]for x in edges);C=sum(x[3]for x in edges)
        insist(K>=0 and K*n+C>0,'No contradiction for every P>=built size')
        insist((K,C,n)==(record['coefficient'],record['constant'],record['built_events']),'False reported affine sum')
        return
    if kind=='read':
        path=record['nodes'];insist(len(path)>1,'Empty conflicting path')
        insist(all(0<=i<n for i in path),'Bad path event')
        insist(all(succ[i]==j for i,j in zip(path,path[1:])),'Path is not consecutive actual updates')
        points=[];letters=[];x=y=0
        for z,i in enumerate(path):
            t,k,h=nodes[i];points.append((x,y));letters.append('R'if k%2==0 else'L')
            nh=(h+(1 if k%2==0 else -1))%4;dx,dy=VECTORS[nh]
            if z+1<len(path):
                nt,_,hh=nodes[path[z+1]]
                insist(hh==nh and nt==t+dx+dy,'Incorrect literal transition')
                insist(volt[i]==dx,'Incorrect translation voltage')
            x+=dx;y+=dy
        insist(points[0]==points[-1] and points[0]not in points[1:-1],'Not consecutive reads of the cell')
        insist(letters[0]==letters[-1],'The two readings do not conflict')
        insist(''.join(letters)==record['word'],'Incorrect displayed forbidden word')
        return
    raise ValueError('Unknown rejection kind '+str(kind))

def verify(obj):
    insist(obj['schema']=='unit-diagonal-three-layer-v1','Unknown schema')
    records={}
    for r in obj['records']:
        key=tuple(r['rows']);insist(key not in records,'Duplicate branch');records[key]=r
    visited=set();counts={str(t):Counter()for t in(-1,-2,-3)};maxn=0;term=[]
    frontier=[()]
    for depth in range(1,4):
        nxt=[]
        for parent in frontier:
            for key in extensions(parent):
                insist(key in records,'Missing enumerated branch '+str(key))
                r=records[key];visited.add(key);graph=reconstruct(key);maxn=max(maxn,len(graph[0]));counts[str(-depth)][r['kind']]+=1
                if r['kind']=='expand':
                    insist(depth<3,'Unclosed terminal branch');nxt.append(key)
                else:
                    validate_negative(graph,r)
                    if r['kind']=='read':term.append(r)
        frontier=nxt
    insist(not frontier,'Unclosed frontier')
    insist(visited==set(records),'Extraneous or inaccessible records')
    insist({k:dict(v)for k,v in counts.items()}==obj['counts'],'Reported counts differ')
    insist(maxn==obj['max_built_events'],'Wrong maximum size')
    insist(sorted(term,key=lambda x:x['rows'])==sorted(obj['terminal_read_conflicts'],key=lambda x:x['rows']),'Terminal transcript mismatch')
    return {'status':'verified','branches':len(visited),'counts':{k:dict(v)for k,v in counts.items()},
            'max_built_events':maxn,'terminal_read_conflicts':len(term),
            'forbidden_words':sorted({r['word']for r in term})}

if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('certificate',type=Path);ap.add_argument('--report',type=Path);args=ap.parse_args()
    raw=args.certificate.read_bytes();report=verify(json.loads(raw));report['certificate_sha256']=hashlib.sha256(raw).hexdigest()
    text=json.dumps(report,indent=2)+'\n';print(text)
    if args.report:args.report.write_text(text)
